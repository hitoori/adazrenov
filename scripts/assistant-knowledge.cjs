const { text } = require('./site-search-index.cjs');

// Only public page copy and catalogue cards become assistant reference material.
// Configuration, scripts, forms, credentials and customer data are never read.
function buildAssistantKnowledge(pages, catalogues, searchRecords) {
  const records = searchRecords.map(record => {
    let content = record.description;
    if (record.type === 'Page') {
      const page = record.href === '/' ? 'index.html' : record.href.slice(1) + '.html';
      const main = pages.get(page)?.match(/<main\b[^>]*>([\s\S]*?)<\/main>/i)?.[1] || '';
      content = text(main.replace(/<form\b[\s\S]*?<\/form>/gi, '').replace(/<iframe\b[\s\S]*?<\/iframe>/gi, ''));
    } else if (record.type === 'Produit') {
      const id = record.href.split('#')[1];
      const product = catalogues.flatMap(catalogue => catalogue.records).find(item => item.id === id);
      content = text((product?.html || '').replace(/<button\b[\s\S]*?<\/button>/gi, ''));
    } else if (record.type === 'Service' || record.type === 'Projet') {
      const page = record.href.split('#')[0].slice(1) + '.html';
      const id = record.href.split('#')[1];
      // Project IDs are also generated by the search index in source order.
      const articles = [...(pages.get(page) || '').matchAll(/<article\b([^>]*)>([\s\S]*?)<\/article>/g)];
      const article = record.type === 'Projet'
        ? articles.filter(match => match[1].includes('data-group="projects"'))[Number(id.replace('projet-', '')) - 1]
        : articles.find(match => match[1].includes(`id="${id}"`));
      content = text(article?.[2] || content);
    }
    return { title: record.title, type: record.type, href: record.href, content: content.slice(0, 8000), keywords: record.keywords || '' };
  });
  return records;
}

module.exports = { buildAssistantKnowledge };
